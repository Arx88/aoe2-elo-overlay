'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('settings', {
  get: () => ipcRenderer.invoke('settings:get'),
  search: (query) => ipcRenderer.invoke('settings:search', query),
  pick: (profileId) => ipcRenderer.invoke('settings:pick', profileId),
  auto: () => ipcRenderer.invoke('settings:auto'),
  theme: (theme) => ipcRenderer.invoke('settings:theme', theme),
  opacity: (value) => ipcRenderer.invoke('settings:opacity', value),
  civHelp: (on) => ipcRenderer.invoke('settings:civHelp', on),
  hideEloAt20: (on) => ipcRenderer.invoke('settings:hideEloAt20', on),
  hideAtSeconds: (seconds) => ipcRenderer.invoke('settings:hideAtSeconds', seconds),
  rivalOption: (key, on) => ipcRenderer.invoke('settings:rivalOption', key, on),
  scoutF2: (on) => ipcRenderer.invoke('settings:scoutF2', on),
  tgBalance: (on) => ipcRenderer.invoke('settings:tgBalance', on),
  postMatchOption: (key, on) => ipcRenderer.invoke('settings:postMatchOption', key, on),
  postmatchGet: () => ipcRenderer.invoke('postmatch:get'),
  postmatchRefresh: () => ipcRenderer.invoke('postmatch:refresh'),
  importTelemetry: () => ipcRenderer.invoke('postmatch:import'),
  activateAccessKey: (key) => ipcRenderer.invoke('settings:activate-access-key', key),
  activateLicense: (account, token) => ipcRenderer.invoke('settings:activate-license', account, token),
  openCommerce: (kind) => ipcRenderer.invoke('settings:open-commerce', kind),
  autoUpdate: (on) => ipcRenderer.invoke('settings:autoUpdate', on),
  exampleStart: (query, clock) => ipcRenderer.invoke('settings:exampleStart', query, clock),
  exampleClock: (mode) => ipcRenderer.invoke('settings:exampleClock', mode),
  exampleStop: () => ipcRenderer.invoke('settings:exampleStop'),
  move: (on) => ipcRenderer.invoke('settings:move', on),
  openLog: () => ipcRenderer.invoke('settings:open-log'),
  onExample: (callback) => ipcRenderer.on('settings:example', (_event, info) => callback(info)),
  onClock: (callback) => ipcRenderer.on('settings:clock', (_event, startedAt) => callback(startedAt)),
  updaterGet: () => ipcRenderer.invoke('updater:get'),
  updaterCheck: () => ipcRenderer.invoke('updater:check'),
  updaterDownload: () => ipcRenderer.invoke('updater:download'),
  updaterInstall: () => ipcRenderer.invoke('updater:install'),
  updaterSkip: () => ipcRenderer.invoke('updater:skip'),
  onUpdater: (callback) => ipcRenderer.on('updater:status', (_event, status) => callback(status)),
  onPostMatch: (callback) => ipcRenderer.on('postmatch:update', (_event, payload) => callback(payload)),
  // Click en la notificación de Windows → salta directo a la pestaña Updater.
  onGoto: (callback) => ipcRenderer.on('settings:goto', (_event, page) => callback(page)),
  minimize: () => ipcRenderer.send('settings:minimize'),
  toggleMaximize: () => ipcRenderer.send('settings:toggle-maximize'),
  onMaximized: (callback) => ipcRenderer.on('settings:maximized', (_event, on) => callback(Boolean(on))),
  close: () => ipcRenderer.send('settings:close'),
});
